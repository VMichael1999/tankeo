    arb[k] = text
    found = re.findall(r'\{(\w+)\}', text)
    if found:
        meta = {'placeholders': {}}
        for name in found:
            kind = ph.get(name, 'String')
            meta['placeholders'][name] = {'type': kind}
        arb['@' + k] = meta
